#!/usr/bin/env python3
"""Generate C training frames, verify the integer model, and export its RTL ROM.

No third-party Python dependencies. Training itself uses train_patterns.py and
PyTorch/CUDA. Verification deliberately operates on the exported 9-bit words.
"""
import argparse
import ctypes
import hashlib
import json
import os
import re
from pathlib import Path
from run import HERE, BUILD, RTL, run

MODEL = HERE / 'learned_model.json'


def reference():
    BUILD.mkdir(exist_ok=True)
    lib = BUILD / 'learned-reference.so'
    run([os.environ.get('CC', 'cc'), '-std=c99', '-O2', '-shared', '-fPIC', HERE / 'reference.c', '-o', lib])
    ref = ctypes.CDLL(str(lib))
    ref.reference_initial.argtypes = [ctypes.c_uint32, ctypes.POINTER(ctypes.c_uint8)]
    ref.reference_step.argtypes = [ctypes.POINTER(ctypes.c_uint8)]
    ref.reference_initial.restype = ref.reference_step.restype = None
    return ref


def frames():
    ref = reference()
    grid = (ctypes.c_uint8 * 960)()
    ref.reference_initial(6502, grid)
    data = [bytes(grid)]
    for _ in range(1280):
        ref.reference_step(grid)
        data.append(bytes(grid))
    return b''.join(data)


def verify(model, blob):
    assert hashlib.sha256(blob).hexdigest() == model['training_sha256']
    assert model['training_seed'] == 6502 and model['training_generations'] == [0, 1280]
    first = model['prediction_source_generation_min']
    end = model['prediction_source_generation_max_exclusive']
    assert 0 <= first < end == 1280
    words = model['rom_words_9bit']
    assert len(words) == 1024 and all(isinstance(w, int) and 0 <= w < 512 for w in words)
    assert bytes(w & 127 for w in words[:960]) == blob[:960]
    assert words[960:] == [0] * 64
    decoded = {1: 0, 2: 1, 3: 100}
    accepted = 0
    for cell, word in enumerate(words[:960]):
        code = word >> 7
        if not code:
            continue
        value = decoded[code]
        for generation in range(first + 1, end + 1):
            assert blob[generation * 960 + cell] == value, (generation, cell, value)
            accepted += 1
    assert accepted == model['accepted_predictions'] == model['correct_accepted_predictions']
    assert accepted / (1280 * 960) == model['training_coverage']
    assert model['accepted_precision'] == 1 and not model['standalone_full_coverage']
    return accepted


def export(model):
    first = model['prediction_source_generation_min']
    end = model['prediction_source_generation_max_exclusive']
    limits = f'''// BEGIN LEARNED LIMITS (generated by eval/learned.py)
localparam [15:0] LEARNED_FIRST = 16'd{first};
localparam [15:0] LEARNED_END = 16'd{end};
// END LEARNED LIMITS'''
    rom = '''// BEGIN LEARNED ROM (generated by eval/learned.py)
module city_learned_rom (
  input wire clk,
  input wire [9:0] address,
  output reg [8:0] q
);
(* ramstyle = "M9K" *) reg [8:0] rom [0:1023];
initial begin
'''
    rom += f'  // seed 6502, generations 0..1280; SHA256 {model["training_sha256"]}\n'
    rom += '\n'.join(f"  rom[{i}] = 9'h{w:03x};" for i, w in enumerate(model['rom_words_9bit']))
    rom += '\nend\nalways @(posedge clk) q <= rom[address];\nendmodule\n// END LEARNED ROM'
    text = RTL.read_text()
    for kind, replacement in [('LIMITS', limits), ('ROM', rom)]:
        text, count = re.subn(f'// BEGIN LEARNED {kind}.*?// END LEARNED {kind}', replacement, text, flags=re.S)
        assert count == 1, (kind, count)
    return text


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('action', choices=['generate', 'verify', 'export'])
    parser.add_argument('--model', type=Path, default=MODEL)
    args = parser.parse_args()
    blob = frames()
    if args.action == 'generate':
        path = BUILD / 'training.bin'
        path.write_bytes(blob)
        print(f'{path}: {len(blob)} bytes, sha256={hashlib.sha256(blob).hexdigest()}')
        return
    model = json.loads(args.model.read_text())
    accepted = verify(model, blob)
    text = export(model)
    if args.action == 'export':
        RTL.write_text(text)
    else:
        assert text == RTL.read_text(), 'RTL model differs from verified export; run learned.py export'
    print(f'PASS integer export: {accepted}/{accepted} accepted predictions exact; '
          f'coverage={model["training_coverage"]:.6%}; 1024 x 9-bit ROM')


if __name__ == '__main__':
    main()
